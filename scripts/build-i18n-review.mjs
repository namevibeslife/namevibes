// Writes docs/i18n-review.md: the long-form content per language, English beside the translation,
// so a native speaker can review it. Run: node scripts/build-i18n-review.mjs
import fs from 'node:fs';

const read = (p) => JSON.parse(fs.readFileSync(p, 'utf8'));
const langs = fs.readdirSync('src/locales').filter(f => f.endsWith('.json') && f !== 'en.json').map(f => f.replace('.json', ''));
const en = read('src/locales/en.json');
const enContent = read('src/locales/content/en.json');
const flat = (o, p = '') => Object.entries(o).flatMap(([k, v]) => (v && typeof v === 'object' ? flat(v, `${p}${k}.`) : [[`${p}${k}`, v]]));
const enFlat = Object.fromEntries(flat(en));

// Which keys are "long-form" and need a careful human read
const GROUPS = [
  ['Element meanings (118)', (k) => k.startsWith('elements.'), true],
  ['Numerology meanings and interpretations', (k) => k.startsWith('numerology.') || k.startsWith('numerologyPage.')],
  ['Zodiac and Vedic astrology', (k) => k.startsWith('zodiac.') || k.startsWith('zodiacPage.') || k.startsWith('astrology.')],
  ['Element and Nakshatra insights', (k) => k.startsWith('insights.')],
  ['Hora and Muhurat', (k) => k.startsWith('hora.')],
  ['Pricing, payment, tax and legal wording', (k) => k.startsWith('pricing.') || k.startsWith('payment.') || /^errors\.(payment|testPayment|monthlyLimit)/.test(k) || k.startsWith('settings.warning') || k.startsWith('settings.clearHint')],
  ['Share and invite messages', (k) => k.startsWith('share.line') || k.startsWith('invite.') || k === 'share.emailSubject'],
  ['Learn more and landing copy', (k) => k.startsWith('learn.') || k.startsWith('landing.')],
  ['AI helper and prompt', (k) => k.startsWith('ai.')],
];

let out = `# Translation review sheet\n\nGenerated by \`node scripts/build-i18n-review.mjs\`. English is the source of truth. Each section lists the long-form text so a native speaker can check tone, accuracy and spelling. Short buttons and labels are in \`src/locales/<code>.json\`; element meanings are in \`src/locales/content/<code>.json\`.\n\nThings that are deliberately **not** translated: the brand name Namasutra/NAMASUTRA, chemical element symbols and names, referral codes, prices and currency codes, the person's typed name, Latin syllable examples for names, place names (cities, states).\n\nTax and payment wording to check carefully: "Includes {{percent}}% GST" (India), "Includes {{percent}}% tax" (other countries), referral line and total.\n\n`;
out += `Languages: ${langs.join(', ')}\n\n`;
for (const lang of langs) {
  const ui = flat(read(`src/locales/${lang}.json`)).reduce((a, [k, v]) => (a[k] = v, a), {});
  const content = flat(read(`src/locales/content/${lang}.json`)).reduce((a, [k, v]) => (a[k] = v, a), {});
  out += `\n---\n\n## ${lang} - ${read(`src/locales/${lang}.json`).meta.name}\n`;
  for (const [title, test, isContent] of GROUPS) {
    const rows = isContent
      ? flat(enContent).filter(([k]) => test(k)).map(([k, v]) => [k, v, content[k]])
      : Object.entries(enFlat).filter(([k]) => !k.startsWith('meta.') && test(k)).map(([k, v]) => [k, v, ui[k]]);
    if (!rows.length) continue;
    out += `\n### ${title}\n\n| Key | English | ${lang} |\n|---|---|---|\n`;
    for (const [k, e, t] of rows) out += `| \`${k}\` | ${String(e).replace(/\|/g, '\\|').replace(/\n/g, ' ')} | ${String(t).replace(/\|/g, '\\|').replace(/\n/g, ' ')} |\n`;
  }
}
fs.mkdirSync('docs', { recursive: true });
fs.writeFileSync('docs/i18n-review.md', out);
console.log('docs/i18n-review.md', Math.round(out.length / 1024), 'KB');
