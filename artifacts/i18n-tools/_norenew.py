for lang, (billing, full) in T.items():
    p = f'src/locales/{lang}.json'
    s = open(p, encoding='utf-8', newline=None).read()
    s, n1 = re.subn(r'(    "billing": )[^\n]*\n', lambda m: m.group(1) + json.dumps(billing, ensure_ascii=False) + ',\n', s, count=1)
    s, n2 = re.subn(r'    "cancelFull": [^\n]*\n', lambda m: '    "noRenewal": ' + json.dumps(full, ensure_ascii=False) + ',\n', s, count=1)
